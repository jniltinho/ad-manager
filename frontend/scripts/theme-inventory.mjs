// Inventory of every color use in the SPA (theme-base): cn-* utilities and variables, literal colors, Tailwind
// palette utilities, text-white and arbitrary shadows, with the contract role each one became.
// Usage: node scripts/theme-inventory.mjs [--base <src dir of the base commit>] > theme-inventory.md
// With --base it lists the base commit's uses (origin) and their destination; the contract is always the current one.
import { readdirSync, readFileSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'

const baseArg = process.argv.indexOf('--base')
const root = baseArg > 0 ? process.argv[baseArg + 1].replace(/\/?$/, '/') : new URL('../src/', import.meta.url).pathname
const files = []
const walk = (d) => {
  for (const f of readdirSync(d)) {
    const p = join(d, f)
    if (statSync(p).isDirectory()) walk(p)
    else if (/\.(vue|css|js)$/.test(f) && !f.endsWith('.test.js') && !p.includes('/locales/')) files.push(p)
  }
}
walk(root)

const palette =
  'slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose'
const rules = [
  [
    'token',
    /(?:^|[\s"'`:])(?:[a-z-]+:)*(?:!?)(?:bg|text|border|border-[tlrbxy]|from|to|via|ring|outline|shadow|fill|stroke|divide|decoration|accent|caret)-cn(?:-[a-z-]+)?(?:\/\d+)?/g,
  ],
  ['var', /var\(--color-cn(?:-[a-z-]+)?\)/g],
  ['literal', /#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)|hsla?\([^)]*\)|oklch\([^)]*\)/g],
  [
    'palette',
    new RegExp(
      `(?:^|[\\s"'\`:])(?:[a-z-]+:)*(?:bg|text|border|from|to|via|ring|fill|stroke|divide)-(?:(?:${palette})-\\d{2,3}|white|black)(?:\\/\\d+)?`,
      'g',
    ),
  ],
  ['shadow', /shadow-\[[^\]]+\]/g],
]
// destination: utilities by name; literals and palette values by the contract roles that default to them
const ROLE = {
  'cn-muted': 'fg-muted',
  'cn-soft': 'fg-subtle',
  'cn-border': 'line',
  'cn-accent': 'accent / focus / header-bar / *-bar',
  'cn-accent-strong': 'accent-strong / link-hover',
  'cn-err': 'err / err-fill / danger',
  'cn-ok': 'ok / ok-fill',
  'cn-warn': 'warn / warn-fill',
  'cn-bg': 'page / row-alt',
  'cn-bg-light': 'surface-2 / line-soft',
  'cn-bg-soft': 'surface-3 / row-hover / action-2',
  cn: 'fg-strong / link / selection / action / strong-fill / chart-1',
  'cn-light': 'action-top / tab-hover / table-head-top',
  'cn-dark': 'action-line / footer / tooltip / tabs-top',
  white: 'surface / field / on-* (text over fills)',
  'slate-900': 'fg',
  'slate-800': 'on-field',
  'red-900': 'danger-line',
}
const contractCss = readFileSync(new URL('../src/style.css', import.meta.url), 'utf8')
const byValue = {}
for (const m of contractCss.matchAll(/(--(?:color|shadow|bg)-[a-z0-9-]+):\s*([^;]+);/g))
  (byValue[m[2].trim().toLowerCase()] ||= []).push(m[1])
function destination(kind, m) {
  if (kind === 'token' || kind === 'palette') {
    const name = m
      .replace(/^.*?(?:bg|text|border(?:-[tlrbxy])?|from|to|via|ring|outline|shadow|fill|stroke|divide)-/, '')
      .replace(/\/\d+$/, '')
    return ROLE[name] ? `\`${ROLE[name]}\`` : '—'
  }
  if (kind === 'var') return ROLE[m.replace(/^var\(--color-|\)$/g, '')] ? `\`${ROLE[m.replace(/^var\(--color-|\)$/g, '')]}\`` : '—'
  const hit = byValue[m.toLowerCase()]
  return hit ? hit.map((r) => `\`${r}\``).join(', ') : 'contract role (`style.css`)'
}
const rows = []
for (const f of files) {
  const lines = readFileSync(f, 'utf8').split('\n')
  lines.forEach((l, i) => {
    if (/^\s*(\/\/|\*|\/\*)/.test(l)) return
    for (const [kind, re] of rules) for (const m of l.matchAll(re)) rows.push([relative(root, f), i + 1, kind, m[0].trim()])
  })
}
const byKind = {}
for (const r of rows) byKind[r[2]] = (byKind[r[2]] || 0) + 1
console.log(baseArg > 0 ? '# Color inventory of the base commit, with the destination (generated)\n' : '# Color inventory (generated)\n')
console.log('Generated by `frontend/scripts/theme-inventory.mjs` — do not edit by hand. Each line is a color use that')
console.log(
  'phase A moves to a contract role (`design.md`). When the destination lists more than one role, the exact one depends on\nthe context of the use (text, background, border) — see the phase A diff.\n',
)
console.log('| Kind | Occurrences |\n|---|---|')
for (const [k, n] of Object.entries(byKind)) console.log(`| ${k} | ${n} |`)
console.log(`| **total** | **${rows.length}** |\n`)
console.log('| File:line | Kind | Use | Destination |\n|---|---|---|---|')
for (const [f, l, k, m] of rows)
  console.log(`| \`${f}:${l}\` | ${k} | \`${m.replace(/\|/g, '\\|')}\` | ${destination(k, m).replace(/\|/g, '\\|')} |`)
